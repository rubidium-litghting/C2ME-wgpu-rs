package com.rubidiumlighting.c2me.opts.accel.wgpu.chunkstatus;

import com.ishland.c2me.rewrites.chunksystem.common.ChunkLoadingContext;
import com.ishland.c2me.rewrites.chunksystem.common.ChunkState;
import com.ishland.c2me.rewrites.chunksystem.common.NewChunkStatus;
import com.ishland.flowsched.scheduler.Cancellable;
import com.ishland.flowsched.scheduler.ItemHolder;
import com.ishland.flowsched.scheduler.KeyStatusPair;
import com.rubidiumlighting.c2me.opts.accel.wgpu.config.Config;
import io.reactivex.rxjava3.core.Completable;
import net.minecraft.util.math.ChunkPos;
import net.minecraft.world.chunk.ChunkGenerationSteps;
import net.minecraft.world.chunk.ChunkStatus;
import net.minecraft.world.chunk.GenerationDependencies;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import java.util.ArrayList;
import java.util.List;
import java.util.concurrent.atomic.AtomicBoolean;

/**
 * C2ME chunk-system integration at the {@code NOISE} boundary.
 *
 * <p>Two modes, selected by {@code chunk_batch_size} in the config:
 *
 * <ul>
 *   <li><b>1 (default)</b> — transparent delegate. The status sits between
 *       vanilla {@code BIOMES} and {@code NOISE} and forwards everything to
 *       C2ME's {@code VanillaWorldGenerationDelegate(NOISE)}. GPU work stays
 *       in the existing {@code populateNoise} →
 *       {@link com.rubidiumlighting.c2me.opts.accel.wgpu.WgpuBatchCoordinator}
 *       path. This is the stage-1 behaviour that was verified in game.</li>
 *   <li><b>2 / 4 / 8</b> — aligned spatial batches. Chunks are grouped into
 *       {@code N×N} squares whose minimum corner is aligned to {@code N}
 *       ({@code (x & (N-1)) == 0 && (z & (N-1)) == 0}). Only that anchor
 *       advances through this status; the other members depend on the anchor
 *       at this same status. The anchor declares the <em>union</em> of the
 *       vanilla {@code NOISE} generation dependencies for the whole group,
 *       then asks the vanilla delegate to generate every member (in parallel,
 *       each with its own member {@code ChunkLoadingContext}). The vanilla
 *       delegate still does all the real work — sampler construction,
 *       aquifer, beardifier, write-back — and still leaves the GPU request in
 *       {@code populateNoise}. Batching changes <em>when</em> the scheduler
 *       considers the group ready, not <em>how</em> a chunk is generated.</li>
 * </ul>
 *
 * <p>Members are never left behind: any member the anchor skips (already at
 * {@code NOISE}, no holder yet, or a group whose anchor was itself loaded
 * from disk) is still generated by the vanilla {@code NOISE} delegate that
 * follows this status in the pipeline. That status remains the correctness
 * backstop, which is why this optimisation cannot leave a chunk ungenerated.
 *
 * <p>Dependencies are derived from the public vanilla API
 * ({@code ChunkGenerationSteps.GENERATION.get(NOISE).directDependencies()});
 * the union is the same {@code (N+16)²-1} square vanilla would require for a
 * single chunk, expanded by {@code N-1} in both directions and assigned the
 * status of the nearest member. Nothing here is copied from another mod's
 * implementation.
 */
public final class WgpuNoiseStatus extends NewChunkStatus {
    private static final Logger LOGGER = LoggerFactory.getLogger("c2me-wgpu-status");
    private static final AtomicBoolean ANNOUNCED = new AtomicBoolean();

    /**
     * Resolved lazily on the first scheduler call. It cannot be resolved in
     * the constructor: the constructor runs from {@code NewChunkStatus.<clinit>}
     * while the hook is about to append the vanilla NOISE delegate, so
     * {@code VANILLA_WORLDGEN_PIPELINE[NOISE]} is still null at that moment.
     */
    private static volatile NewChunkStatus vanillaNoise;

    /** Chunks per side in one aligned batch. 1 = transparent delegate. */
    private final int batchSize;
    /** {@code batchSize - 1}; used for power-of-two alignment. */
    private final int batchMask;
    /**
     * Dependencies of a batch anchor, in positions relative to the anchor:
     * every offset in {@code [-(r), (batchSize-1)+r]} on both axes where
     * {@code r} is the vanilla NOISE dependency radius, excluding the anchor
     * itself. Precomputed because it is immutable for this status instance.
     */
    private final KeyStatusPair<ChunkPos, ChunkState, ChunkLoadingContext>[] batchDeps;

    public WgpuNoiseStatus(int ordinal) {
        super(ordinal, ChunkStatus.NOISE);
        int configured = Config.get().chunkBatchSize;
        // Config#clamp normalises the file, but never trust it here: an
        // unexpected value must degrade to the verified single-chunk path
        // rather than compute a wrong alignment mask.
        this.batchSize = (configured == 2 || configured == 4 || configured == 8)
                ? configured : 1;
        this.batchMask = this.batchSize - 1;
        this.batchDeps = buildBatchDependencies(this.batchSize);
    }

    private static NewChunkStatus vanillaNoise() {
        NewChunkStatus s = vanillaNoise;
        if (s == null) {
            s = NewChunkStatus.fromVanillaStatus(ChunkStatus.NOISE);
            vanillaNoise = s;
        }
        return s;
    }

    /**
     * Build the dependency set a batch anchor must satisfy. For a single
     * chunk this reproduces the vanilla {@code NOISE} generation dependencies
     * exactly; for a batch it is the union over all members.
     *
     * <p>The list is built here, so every element really is a {@code
     * KeyStatusPair<ChunkPos, ChunkState, ChunkLoadingContext>}; only the
     * array type itself is erased.
     */
    @SuppressWarnings("unchecked")
    private static KeyStatusPair<ChunkPos, ChunkState, ChunkLoadingContext>[] buildBatchDependencies(int size) {
        GenerationDependencies direct =
                ChunkGenerationSteps.GENERATION.get(ChunkStatus.NOISE).directDependencies();
        int radius = direct.getMaxLevel();
        int span = size - 1;
        int lo = -radius;
        int hi = span + radius;
        int width = hi - lo + 1;
        List<KeyStatusPair<ChunkPos, ChunkState, ChunkLoadingContext>> deps =
                new ArrayList<>(width * width - 1);
        for (int x = lo; x <= hi; x++) {
            for (int z = lo; z <= hi; z++) {
                if (x == 0 && z == 0) {
                    continue; // the anchor itself, not a dependency
                }
                // Chebyshev distance from this offset to the group square
                // [0, span] x [0, span]. Clamped at zero because a position
                // inside the square is distance zero (all members need the
                // same radius-0/1 status).
                int dx = Math.max(0, Math.max(-x, x - span));
                int dz = Math.max(0, Math.max(-z, z - span));
                int distance = Math.max(dx, dz);
                deps.add(new KeyStatusPair<>(
                        new ChunkPos(x, z),
                        fromVanillaStatus(direct.get(distance))));
            }
        }
        return deps.toArray(KeyStatusPair[]::new);
    }

    private boolean isAnchor(ChunkPos pos) {
        return (pos.x & batchMask) == 0 && (pos.z & batchMask) == 0;
    }

    private ChunkPos anchorOf(ChunkPos pos) {
        return new ChunkPos(pos.x & ~batchMask, pos.z & ~batchMask);
    }

    private void announceOnce() {
        if (!ANNOUNCED.compareAndSet(false, true)) {
            return;
        }
        if (batchSize == 1) {
            LOGGER.info("[c2me-wgpu-status] active: ordinal={}, batch_size=1 "
                    + "(delegating vanilla NOISE; GPU work stays in populateNoise)", ordinal());
        } else {
            LOGGER.info("[c2me-wgpu-status] active: ordinal={}, batch_size={} "
                            + "({}x{} chunks per anchor, {} dependencies per group)",
                    ordinal(), batchSize, batchSize, batchSize, batchDeps.length);
        }
    }

    @Override
    public Completable upgradeToThis(ChunkLoadingContext ctx, Cancellable cancellable) {
        NewChunkStatus vanilla = vanillaNoise();
        if (vanilla == null || vanilla == this) {
            // Should be impossible after NewChunkStatus.<clinit>; completing
            // without doing work lets the scheduler advance to the real
            // vanilla NOISE delegate instead of deadlocking.
            LOGGER.warn("[c2me-wgpu-status] vanilla NOISE delegate unavailable");
            return Completable.complete();
        }
        announceOnce();

        ChunkPos pos = ctx.holder().getKey();
        if (batchSize == 1) {
            StatusNoiseContext.observe(ctx);
            return vanilla.upgradeToThis(ctx, cancellable);
        }
        if (!isAnchor(pos)) {
            // The anchor already generated every member of the group when it
            // passed this status, or those it could not will be generated by
            // the vanilla NOISE delegate immediately after this one.
            return Completable.complete();
        }

        ChunkState anchorState = ctx.holder().getItem().get();
        if (anchorState == null) {
            // Not expected past DISK, but returning complete is the safe
            // fallback: the next status re-checks the state itself.
            LOGGER.warn("[c2me-wgpu-status] anchor {} has no ChunkState; "
                    + "leaving the group to the vanilla NOISE delegate", pos);
            return Completable.complete();
        }
        if (anchorState.reachedStatus().isAtLeast(ChunkStatus.NOISE)) {
            // Already generated (typically loaded from disk). Members not yet
            // generated are handled one by one by the next status.
            return Completable.complete();
        }

        StatusNoiseContext.observe(ctx);

        List<Completable> work = new ArrayList<>(batchSize * batchSize);
        for (int dx = 0; dx < batchSize; dx++) {
            for (int dz = 0; dz < batchSize; dz++) {
                if (dx == 0 && dz == 0) {
                    work.add(vanilla.upgradeToThis(ctx, cancellable));
                    continue;
                }
                ChunkPos memberPos = new ChunkPos(pos.x + dx, pos.z + dz);
                ItemHolder<ChunkPos, ChunkState, ChunkLoadingContext, ?> holder =
                        ctx.theChunkSystem().getHolder(memberPos);
                if (holder == null) {
                    LOGGER.warn("[c2me-wgpu-status] batch member {} of anchor {} "
                            + "has no holder; it will be generated individually", memberPos, pos);
                    continue;
                }
                ChunkState memberState = holder.getItem().get();
                if (memberState == null) {
                    LOGGER.warn("[c2me-wgpu-status] batch member {} of anchor {} "
                            + "has no ChunkState; it will be generated individually", memberPos, pos);
                    continue;
                }
                if (memberState.reachedStatus().isAtLeast(ChunkStatus.NOISE)) {
                    continue; // already generated; nothing to do
                }
                ChunkLoadingContext memberCtx = new ChunkLoadingContext(
                        holder, ctx.tacs(), ctx.schedulingManager(),
                        ctx.theChunkSystem(), ctx.dependencies());
                work.add(vanilla.upgradeToThis(memberCtx, cancellable));
            }
        }

        if (work.isEmpty()) {
            return Completable.complete();
        }
        if (work.size() == 1) {
            return work.get(0);
        }
        // Subscribe to all members at once. At NOISE the vanilla write radius
        // is 0, so the per-member lock sets are disjoint and the scheduler can
        // run them concurrently; the GPU coordinator then sees the whole
        // group within one gather window.
        return Completable.merge(work);
    }

    /**
     * {@inheritDoc}
     *
     * <p>The generic array type is part of C2ME's own interface, so creating
     * and returning it is unavoidably unchecked; every element is built here
     * as a {@code KeyStatusPair<ChunkPos, ChunkState, ChunkLoadingContext>}.
     */
    @Override
    @SuppressWarnings("unchecked")
    public KeyStatusPair<ChunkPos, ChunkState, ChunkLoadingContext>[] getDependencies(
            ItemHolder<ChunkPos, ChunkState, ChunkLoadingContext, ?> holder) {
        ChunkState state = holder.getItem().get();
        if (state != null && state.reachedStatus().isAtLeast(ChunkStatus.NOISE)) {
            // Nothing to wait for; the next status will no-op.
            return EMPTY_DEPENDENCIES;
        }

        if (batchSize > 1 && !isAnchor(holder.getKey())) {
            ChunkPos pos = holder.getKey();
            ChunkPos anchor = anchorOf(pos);
            KeyStatusPair<ChunkPos, ChunkState, ChunkLoadingContext> dep =
                    new KeyStatusPair<>(
                            new ChunkPos(anchor.x - pos.x, anchor.z - pos.z),
                            this);
            return relativeToAbsoluteDependencies(
                    holder,
                    new KeyStatusPair[]{dep});
        }

        return relativeToAbsoluteDependencies(holder, batchDeps);
    }

    @Override
    public Completable postUpgradeToThis(ChunkLoadingContext ctx) {
        return Completable.complete();
    }

    @Override
    public Completable preDowngradeFromThis(ChunkLoadingContext ctx, Cancellable cancellable) {
        return Completable.complete();
    }

    @Override
    public Completable downgradeFromThis(ChunkLoadingContext ctx, Cancellable cancellable) {
        return Completable.complete();
    }

    @Override
    public String toString() {
        return "c2me-wgpu:wgpu_noise";
    }
}
