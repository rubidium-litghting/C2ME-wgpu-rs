package com.rubidiumlighting.c2me.opts.accel.wgpu.mixin;

import net.minecraft.util.math.noise.SimplexNoiseSampler;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.gen.Accessor;

/**
 * Accessor for {@link SimplexNoiseSampler}'s private {@code permutation}
 * table. String reflection fails on intermediary names at runtime; the
 * {@code @Accessor} value is remapped by Loom and resolves correctly.
 * ({@code originX/Y/Z} are public fields, so they need no accessor.)
 */
@Mixin(SimplexNoiseSampler.class)
public interface SimplexNoiseSamplerAccessor {
    @Accessor("permutation")
    int[] getPermutation();
}
