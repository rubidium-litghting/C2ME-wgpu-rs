package com.rubidiumlighting.c2me.opts.accel.wgpu.config;

import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

/**
 * Marks a {@link Config} field as a user-facing setting.
 *
 * <p>The ModMenu screen is generated by reflecting over the annotated fields,
 * so this annotation — not the GUI code — decides what the player can change.
 * Adding a setting means adding a field here; the screen picks it up with no
 * further edits.
 *
 * <p>Which screen a field appears on is derived from its
 * {@code @SerializedName}: anything starting with {@code debug_} goes to the
 * debug screen, everything else to the main one. Deriving it from the JSON key
 * rather than a second annotation means a new {@code debug_} setting can never
 * end up on the wrong screen by forgetting to tag it.
 */
@Retention(RetentionPolicy.RUNTIME)
@Target(ElementType.FIELD)
public @interface ConfigOption {

    /** Translation key for the row label. */
    String label();

    /** Which widget to build. */
    Kind kind() default Kind.BOOL;

    /** Sort order in the screen; lower comes first. */
    int order() default 100;

    enum Kind {
        /** Boolean on/off toggle. */
        BOOL,
        /** Automatic GPU selection plus one entry per adapter. */
        GPU_INDEX,
        /** {@code null} / true / false, e.g. {@code mapped_at_creation}. */
        TRI_STATE,
        /** Free-form text, rendered as a text field. */
        STRING
    }
}
